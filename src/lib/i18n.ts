/**
 * Interface strings in Portuguese and English. The chosen language lives in a cookie so server
 * components can read it directly; `LangProvider` hands the same value to client components.
 *
 * `pt` is the source of truth: `en` is typed against it, so a missing key is a compile error.
 * Keep the values here and never inline user-facing text in a component.
 */
export const LANGS = ["pt", "en"] as const;
export type Lang = (typeof LANGS)[number];
export const DEFAULT_LANG: Lang = "pt";
export const LANG_COOKIE = "brain_lang";

export function isLang(v: string | undefined | null): v is Lang {
  return v === "pt" || v === "en";
}

